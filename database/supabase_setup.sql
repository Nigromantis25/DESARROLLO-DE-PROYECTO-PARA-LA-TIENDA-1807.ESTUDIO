CREATE OR REPLACE FUNCTION public.update_fecha_actualizacion()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    NEW.fecha_actualizacion = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS update_admin_vault_timestamp ON public.admin_vault;
CREATE TRIGGER update_admin_vault_timestamp
BEFORE UPDATE ON public.admin_vault
FOR EACH ROW EXECUTE FUNCTION public.update_fecha_actualizacion();

DROP TRIGGER IF EXISTS update_admin_settings_timestamp ON public.admin_settings;
CREATE TRIGGER update_admin_settings_timestamp
BEFORE UPDATE ON public.admin_settings
FOR EACH ROW EXECUTE FUNCTION public.update_fecha_actualizacion();

