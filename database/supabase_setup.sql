    EXISTS (
        SELECT 1 FROM public.cliente c
        WHERE c.idcliente = carrito.idcliente
          AND c.idusuario = (SELECT auth.uid())
    )
)
WITH CHECK (
    EXISTS (
        SELECT 1 FROM public.cliente c
        WHERE c.idcliente = carrito.idcliente
          AND c.idusuario = (SELECT auth.uid())
    )
);

