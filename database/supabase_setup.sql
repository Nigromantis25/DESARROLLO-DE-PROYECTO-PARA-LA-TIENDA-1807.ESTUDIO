CREATE TABLE IF NOT EXISTS public.rol (
    idrol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(100) NOT NULL,
    fecharegistro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.permiso (
    idpermiso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idrol BIGINT NOT NULL REFERENCES public.rol(idrol) ON DELETE CASCADE,
    acceso VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    role TEXT NOT NULL DEFAULT 'client'
);

CREATE TABLE IF NOT EXISTS public.usuario (
    idusuario UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    nombre VARCHAR(100) NOT NULL,
    apellido_p VARCHAR(100),
    apellido_m VARCHAR(100),
    telefono VARCHAR(20),
    documento VARCHAR(50),
    correo VARCHAR(255) UNIQUE,
    estado SMALLINT NOT NULL DEFAULT 1,
    fecharegistro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.cliente (
    idcliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idusuario UUID NOT NULL UNIQUE REFERENCES public.usuario(idusuario) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.empleado (
    idempleado BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idusuario UUID NOT NULL UNIQUE REFERENCES public.usuario(idusuario) ON DELETE CASCADE,
    idrol BIGINT NOT NULL REFERENCES public.rol(idrol)
);

CREATE OR REPLACE FUNCTION public.handle_new_auth_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    nombre_usuario TEXT;
BEGIN
    nombre_usuario := COALESCE(
        NULLIF(NEW.raw_user_meta_data ->> 'nombre', ''),
        NULLIF(split_part(COALESCE(NEW.email, ''), '@', 1), ''),
        'Cliente'
    );

    INSERT INTO public.profiles (id, role)
    VALUES (NEW.id, 'client')
    ON CONFLICT (id) DO NOTHING;

    INSERT INTO public.usuario (idusuario, nombre, correo)
    VALUES (NEW.id, nombre_usuario, NEW.email)
    ON CONFLICT (idusuario) DO NOTHING;

    INSERT INTO public.cliente (idusuario)
    VALUES (NEW.id)
    ON CONFLICT (idusuario) DO NOTHING;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created_1807 ON auth.users;
CREATE TRIGGER on_auth_user_created_1807
AFTER INSERT ON auth.users
FOR EACH ROW
EXECUTE FUNCTION public.handle_new_auth_user();

INSERT INTO public.profiles (id, role)
SELECT id, 'client' FROM auth.users
ON CONFLICT (id) DO NOTHING;

INSERT INTO public.usuario (idusuario, nombre, correo)
SELECT
    id,
    COALESCE(
        NULLIF(raw_user_meta_data ->> 'nombre', ''),
        NULLIF(split_part(COALESCE(email, ''), '@', 1), ''),
        'Cliente'
    ),
    email
FROM auth.users
ON CONFLICT (idusuario) DO NOTHING;

INSERT INTO public.cliente (idusuario)
SELECT idusuario FROM public.usuario
ON CONFLICT (idusuario) DO NOTHING;

